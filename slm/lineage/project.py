#!/usr/bin/env python3
"""ADR-0035 §1: project a lineage record from the reference mechanism's log, and cross-check the
author's manifest against it.

    uv run lineage/project.py --archive rehearsal/run/pg/run/n2/archive.jsonl \
        --params rehearsal/run/pg/params.json --corpus-json data/corpora/pg19@rehearsal/corpus.json \
        --workspaces rehearsal/run/pg/run/n1/workspaces --seat a1 --lineage R-pg \
        --manifest rehearsal/run/pg/result-honest/manifest.json --out rehearsal/run/pg/result-honest

What comes from where:

  round, lease, rung   the Grant (and any Renew) entries for the seat's round
  ingress              the corpus root in force: params.json, checked against the `params` digest
                       every admit carries. Over-approximated (§2): the round is charged with every
                       object it *could* read, not just the ones it did (those are kept as
                       `attributed`). Drafts into the tool's corpus directory that are not
                       byte-copies of a Read object are charged too, as content generated by the
                       author's Persona. Draft is an ingress channel the corpus root does not bound
  generatedBy etc.     each ingress object's admission declaration (corpus.json): declared at
                       admission, as §1 allows for external objects
  trainer              the slm_pretrain Invoke: tool id from the admit, config found by matching
                       the admit's inputs digest against the round's drafted config paths, and
                       the config bytes checked against that Draft's content digest
  tokenizer, root,     files in the submitted workspace, after checking the workspace digest
  weights              equals the Submit's artifact. The workspace lives only on the replica
                       that ran the effects (G9), so this is the one input not from the log
  family               the pretrain config's `model.family` (declared: §1 says the tag is a claim)

Output: `lineage.projected.json` (the record) and `crosscheck.json`. The verdict is `consistent`,
or `Contested` with each divergence attributed to the seat, lease and log slot. Exit status 0,
or 4 when Contested. A rung-0 round makes the record `declared` whatever else holds (§2).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import record  # noqa: E402
from common import sha256_bytes, sha256_file, sha256_json, tree_digest, write_json  # noqa: E402
from model import FAMILY_TAGS  # noqa: E402

# The reference's `canonical_json` is not key-sorted: cedar-policy-core 4.13 turns on serde_json's
# `preserve_order`, so maps keep insertion order and a struct serializes in field order. The params
# digest in every admit is therefore over `Params`' fields in declaration order (state.rs). A
# single-key object, like every SLM tool's inputs, is unaffected.
PARAMS_FIELDS = ("corpus", "build_tools", "run_tools", "round_bound", "lease_margin_ms", "after_topic_limit")

TOOL_ROLES = {"slm_tokenizer": "tokenizer", "slm_pretokenize": "pretokenize", "slm_pretrain": "pretrain"}


class Unprojectable(Exception):
    pass


def load_archive(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()]


def grant_round(req: dict) -> tuple[int, str]:
    if "assignment" in req:  # archives written before ADR-0031 R1 folded round and role into the lease
        return req["assignment"]["round"], req["assignment"]["role"]
    return req["round"], req["role"]


def round_slice(entries: list[dict], seat: str, round_: int | None) -> dict:
    """The seat's round: its leases (grant + renewals), and every admit under them, in log order."""
    grants = [e for e in entries if e["entry"]["entry"] == "Grant" and e["entry"]["req"]["seat"] == seat
              and "LeaseGranted" in (e["applied"] if isinstance(e["applied"], dict) else {})]
    if round_ is not None:
        grants = [g for g in grants if grant_round(g["entry"]["req"])[0] == round_]
    if not grants:
        raise Unprojectable(f"no granted lease for seat {seat}" + (f" round {round_}" if round_ else ""))
    g = grants[-1]
    fences = {g["applied"]["LeaseGranted"]["fence"]}
    rungs = [g["entry"]["req"]["confinement"]["rung"]]
    for e in entries:
        en = e["entry"]
        if en["entry"] == "Renew" and en["req"]["fence"] in fences and isinstance(e["applied"], dict) \
                and "Renewed" in e["applied"]:
            fences.add(e["applied"]["Renewed"]["fence"])
            rungs.append(en["req"]["rung"])
    admits = [e for e in entries if e["entry"]["entry"] == "Admit" and e["entry"]["rec"]["lease"] in fences
              and isinstance(e["applied"], dict) and "Admitted" in e["applied"]]
    rnd, role = grant_round(g["entry"]["req"])
    return {"grant": g, "fences": sorted(fences), "rung": min(rungs), "round": rnd, "role": role, "admits": admits,
            "epoch": admits[0]["entry"]["rec"]["epoch"] if admits else None,
            "persona": g["entry"]["req"]["persona"]}


def project(a) -> tuple[dict, dict]:
    entries = load_archive(a.archive)
    sl = round_slice(entries, a.seat, a.round)
    params = json.loads(a.params.read_text())
    params.setdefault("after_topic_limit", 64)
    for k in ("corpus", "build_tools", "run_tools"):
        params[k] = sorted(params[k])
    in_order = {k: params[k] for k in PARAMS_FIELDS}
    pdig = sha256_bytes(json.dumps(in_order, separators=(",", ":"), ensure_ascii=False).encode())
    facts = {"seat": a.seat, "round": sl["round"], "role": sl["role"], "leases": sl["fences"], "rung": sl["rung"],
             "params": pdig, "slots": [e["slot"] for e in sl["admits"]]}

    bad = sorted({e["entry"]["rec"]["params"] for e in sl["admits"]} - {pdig})
    if bad:
        raise Unprojectable(f"admits carry params digest {bad[0][:16]}, not {pdig[:16]} from {a.params}")

    reads, drafts, invokes, submit = [], [], [], None
    for e in sl["admits"]:
        act = e["entry"]["rec"]["action"]
        k = act["kind"]
        if k == "Read":
            reads.append((e["slot"], act["object"]))
        elif k == "Draft":
            drafts.append((e["slot"], act["target"], act["content"]))
        elif k == "Invoke":
            invokes.append((e["slot"], act["tool"], act["inputs"]))
        elif k == "Submit":
            submit = (e["slot"], act["artifact"])
    if submit is None:
        raise Unprojectable("the round has no Submit, so there is no artifact to attribute")

    # The workspace: the one input not in the log. Bound to it by the submitted digest.
    ws = a.workspaces / f"ws-{a.seat}-e{sl['epoch']}-r{sl['round']}"
    if not ws.is_dir():
        raise Unprojectable(f"workspace {ws} not found (it lives on the replica that ran the effects, G9)")
    wd = tree_digest(ws)
    if wd != submit[1]:
        raise Unprojectable(f"workspace digest {wd[:16]} is not the submitted artifact {submit[1][:16]}")

    # Each Invoke's config: the drafted path whose {"config": path} digest is the admit's inputs.
    steps = {}
    for slot, tool, inputs in invokes:
        name = tool.split("@")[0]
        role = TOOL_ROLES.get(name)
        if role is None:
            raise Unprojectable(f"slot {slot}: Invoke of {tool}, which this projector has no contract for")
        prior = [(s, t, c) for s, t, c in drafts if s < slot]
        match = [(s, t, c) for s, t, c in prior if sha256_json({"config": t}) == inputs]
        if not match:
            raise Unprojectable(f"slot {slot}: no drafted path gives inputs digest {inputs[:16]}")
        _, target, _ = match[-1]
        last = [(s, c) for s, t, c in prior if t == target][-1]
        body = (ws / target).read_bytes()
        if sha256_bytes(body) != last[1]:
            raise Unprojectable(f"{target} in the workspace is not the bytes drafted at slot {last[0]}")
        steps[role] = {"slot": slot, "tool": tool, "config_path": target, "config": last[1],
                       "content": json.loads(body)}
    for need in ("tokenizer", "pretrain"):
        if need not in steps:
            raise Unprojectable(f"the round has no {need} Invoke")

    # Ingress: the corpus root in force (over-approximated), plus authored drafts into the data dirs.
    decl = json.loads(a.corpus_json.read_text())
    sizes = {o["digest"]: o["bytes"] for o in decl["objects"]}
    root_objs = params["corpus"]
    missing = [d for d in root_objs if d not in sizes]
    ingress = [record.ingress_entry(d, sizes.get(d, (Path(a.params).parent / "corpus" / d).stat().st_size),
                                    None if d in missing else decl["declaration"], decl["id"]) for d in root_objs]
    read_set = {d for _, d in reads}
    data_dirs = {steps[r]["content"].get("objects") for r in ("tokenizer", "pretokenize") if r in steps} - {None}
    copies, authored = [], []
    for slot, target, content in drafts:
        if not any(target == d or target.startswith(d.rstrip("/") + "/") for d in data_dirs):
            continue
        (copies if content in read_set else authored).append({"slot": slot, "target": target, "digest": content})
    for d in authored:
        size = (ws / d["target"]).stat().st_size if (ws / d["target"]).exists() else 0
        ingress.append(record.ingress_entry(
            d["digest"], size, {"generators": [f"persona:{sl['persona']}"], "generated_share": 1.0, "curators": []},
            corpus=f"draft:{a.seat}@slot{d['slot']}"))

    pre = steps["pretrain"]["content"]
    tok_path = ws / steps["tokenizer"]["content"]["out"] / "tokenizer.json"
    ckpt = ws / pre["out"]
    init_from = pre.get("init_from")
    if init_from:
        raise Unprojectable("a fine-tune round needs its parent's record; not supported by this rehearsal")
    rec = record.build(
        lineage=a.lineage,
        strength="projected",
        rung=sl["rung"],
        root=sha256_file(ckpt / "init.safetensors"),
        weights=sha256_file(ckpt / "model.safetensors"),
        tokenizer=sha256_file(tok_path),
        family=FAMILY_TAGS[pre["model"]["family"]],
        trainer={"tool": steps["pretrain"]["tool"], "config": steps["pretrain"]["config"], "seed": pre.get("seed")},
        ingress=ingress,
        nodes=[{"kind": role, "slot": s["slot"], "tool": s["tool"], "config": s["config"]}
               for role, s in sorted(steps.items(), key=lambda kv: kv[1]["slot"])],
        evidence={"source": "projected from the log", **facts, "artifact": submit[1], "submit_slot": submit[0],
                  "attributed_reads": sorted(read_set), "copies": len(copies), "authored_drafts": authored,
                  "note": "rung 0: the projection is attribution, not a bound (ADR-0035 §2)" if sl["rung"] == 0 else ""},
    )
    return rec, {"steps": steps, "reads": reads, "authored": authored, "submit": submit, "slice": sl}


def crosscheck(rec: dict, ctx: dict, m: dict) -> dict:
    """Compare the author's claims with the projection. Each divergence names where in the log
    the evidence is."""
    div = []
    seat, lease = rec["evidence"]["seat"], rec["evidence"]["leases"][-1]

    def diverge(field, claimed, projected, slot):
        div.append({"field": field, "claimed": claimed, "projected": projected,
                    "attribution": {"seat": seat, "lease": lease, "slot": slot}})

    claimed = {o["digest"] for c in m["corpus"] for o in c["objects"]}
    ingress = {e["digest"] for e in rec["ingress"]}
    used = {d for _, d in ctx["reads"]} | {d["digest"] for d in ctx["authored"]}
    for d in sorted(used - claimed):
        slot = next((s for s, o in ctx["reads"] if o == d), None) or next(
            (x["slot"] for x in ctx["authored"] if x["digest"] == d), None)
        diverge("corpus", "absent", d, slot)
    for d in sorted(claimed - ingress):
        diverge("corpus", d, "outside the corpus root", None)
    st = ctx["steps"]
    checks = [
        ("tokenizer", m["tokenizer"]["digest"], rec["tokenizer"], st["tokenizer"]["slot"]),
        ("config", m["config"]["digest"], rec["trainer"]["config"], st["pretrain"]["slot"]),
        ("seed", m["seed"], rec["trainer"]["seed"], st["pretrain"]["slot"]),
        ("family", m["family"], rec["family"], st["pretrain"]["slot"]),
        ("root", m["model"]["root"], rec["root"], st["pretrain"]["slot"]),
        ("weights", m["model"]["weights"], rec["weights"], ctx["submit"][0]),
        ("trainer tool", m.get("tools", {}).get("slm_pretrain"), rec["trainer"]["tool"], st["pretrain"]["slot"]),
    ]
    for field, c, p, slot in checks:
        if c != p:
            diverge(field, c, p, slot)
    return {"schema": "topak.lineage-crosscheck/0", "lineage": rec["lineage"], "record": rec["digest"],
            "verdict": "Contested" if div else "consistent", "divergences": div,
            "strength": rec["strength"], "rung": rec["rung"]}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--archive", required=True, type=Path, help="a replica's archive.jsonl (a projection of the log)")
    ap.add_argument("--params", required=True, type=Path)
    ap.add_argument("--corpus-json", required=True, type=Path, help="admission declarations for the corpus root")
    ap.add_argument("--workspaces", required=True, type=Path, help="the deciding replica's workspaces directory")
    ap.add_argument("--seat", required=True)
    ap.add_argument("--round", type=int)
    ap.add_argument("--lineage", required=True)
    ap.add_argument("--manifest", type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()

    try:
        rec, ctx = project(a)
    except Unprojectable as e:
        print(f"not projectable: {e}", file=sys.stderr)
        sys.exit(5)
    write_json(a.out / "lineage.projected.json", rec)
    ev = rec["evidence"]
    print(f"projected {rec['lineage']}: record {rec['digest'][:16]}  strength {rec['strength']} (rung {rec['rung']})")
    print(f"  slots {ev['slots'][0]}–{ev['slots'][-1]} under lease {ev['leases']}, params {ev['params'][:12]}")
    print(f"  ingress {len(rec['ingress'])} objects ({rec['ingress_bytes'] / 1e6:.1f} MB, corpus root), "
          f"{len(ev['attributed_reads'])} read, {len(ev['authored_drafts'])} authored drafts")
    print(f"  root {rec['root'][:16]}  weights {rec['weights'][:16]}  tokenizer {rec['tokenizer'][:16]}  "
          f"family {rec['family']}")
    print(f"  generatedBy {rec['generatedBy'] or '∅'}  curatedBy {rec['curatedBy'] or '∅'}")
    if not a.manifest:
        return
    cc = crosscheck(rec, ctx, json.loads(a.manifest.read_text()))
    write_json(a.out / "crosscheck.json", cc)
    print(f"cross-check against the authored manifest: {cc['verdict']}")
    for d in cc["divergences"]:
        at = d["attribution"]
        print(f"  {d['field']}: claimed {str(d['claimed'])[:20]}, projected {str(d['projected'])[:24]}  "
              f"(seat {at['seat']}, lease {at['lease']}, slot {at['slot']})")
    sys.exit(4 if cc["verdict"] == "Contested" else 0)


if __name__ == "__main__":
    main()
