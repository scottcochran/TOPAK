#!/usr/bin/env python3
"""Build a three-replica reference cluster for one rehearsal lineage.

    uv run rehearsal/init.py --name pg --corpus data/corpora/pg19@rehearsal

Writes rehearsal/run/<name>/ and touches nothing in mechanism/ or policies/:

  corpus/<sha256>          the lineage's corpus root: the shards, unchanged
  tool/topak-slm-tool      the pinned wrapper around slm_tool.py (see slm_tool.py)
  policies/, bundles/      the repository's bundle policies plus schemas for the three SLM tools,
                           built with mechanism/scripts/build-bundle.sh (needs Docker)
  secrets/, rules.json     DEV keys and rules, as mechanism/scripts/dev-init.sh makes them. The
                           secrets are in the clear. These are not genesis rules
  params.json              corpus root, build-tool allowlist, round bound, lease margin
  n1.json … n3.json        replica configs on ports 7201–7203
  cluster.json             what drive.py and project.py need

Like the dev cluster, it uses the in-memory transport and the local WASM bundle only (no Kafka,
no OPA sidecar).
"""
from __future__ import annotations

import argparse
import json
import pathlib
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
SLM = HERE.parent
REPO = SLM.parent
MECH = REPO / "mechanism"
TOPAK = MECH / "target" / "debug" / "topak"
sys.path.insert(0, str(SLM))
sys.path.insert(0, str(HERE))
from common import load_json, sha256_file, write_json  # noqa: E402
from slm_tool import TOOLS, pinned_digest  # noqa: E402


def run(*args, **kw) -> str:
    return subprocess.run([str(a) for a in args], check=True, capture_output=True, text=True, **kw).stdout.strip()


def pin_tool(dest: pathlib.Path) -> pathlib.Path:
    """Generate the wrapper executable. Its bytes embed the code digest, so the reference's
    binary pin covers the pipeline code the wrapper runs."""
    py = SLM / ".venv" / "bin" / "python"
    if not py.exists():
        sys.exit(f"{py} missing: run `uv sync` in slm/ first")
    dest.mkdir(parents=True, exist_ok=True)
    w = dest / "topak-slm-tool"
    w.write_text(f"""#!{py} -I
# Generated by slm/rehearsal/init.py. The digest below pins slm_tool.py and the pipeline code;
# the wrapper refuses to serve if either has changed. Regenerate with init.py after editing them.
import sys
sys.path[:0] = [{str(SLM)!r}, {str(HERE)!r}]
import slm_tool
slm_tool.main({pinned_digest()!r})
""")
    w.chmod(0o755)
    return w


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True, help="short name; socket paths must stay under 104 bytes")
    ap.add_argument("--corpus", required=True, type=pathlib.Path, help="a prepared corpus directory")
    a = ap.parse_args()

    root = HERE / "run" / a.name
    corpus = load_json(a.corpus / "corpus.json")
    if len(str(root / "run/n1/operator.sock")) > 100:
        sys.exit(f"{root} is too deep for a unix socket path; use a shorter --name")

    print("building topak (cargo, incremental)")
    subprocess.run(["cargo", "build", "-q", "--manifest-path", str(MECH / "Cargo.toml"), "-p", "topak-node"], check=True)

    shutil.rmtree(root, ignore_errors=True)
    for d in ("corpus", "secrets", "run", "bundles", "policies"):
        (root / d).mkdir(parents=True)

    # Corpus root: the shards, byte for byte, named by digest.
    for o in corpus["objects"]:
        src = a.corpus / "objects" / o["digest"]
        assert sha256_file(src) == o["digest"], f"{src} does not match its name"
        shutil.copyfile(src, root / "corpus" / o["digest"])

    # Tools: pin the wrapper, then ask the reference for each allowlist id.
    wrapper = pin_tool(root / "tool")
    tools = {}
    for name in TOOLS:
        td = json.loads(run(TOPAK, "tool-digest", "--command", wrapper, "--tool", name))
        tools[name] = {"id": td["id"], "binary_sha256": td["binary_sha256"]}
        print(f"tool     {td['id']}")

    # Bundle: the repository's policies, plus an input schema per SLM tool.
    for f in (REPO / "policies").glob("*.rego"):
        if not f.name.endswith("_test.rego"):
            shutil.copyfile(f, root / "policies" / f.name)
    data = load_json(REPO / "policies" / "data.json")
    for t in tools.values():
        data["topak"]["tools"][t["id"]] = {"required": {"config": "string"}}
    write_json(root / "policies" / "data.json", data)
    print("building bundle (docker, OPA)")
    rev = run(MECH / "scripts" / "build-bundle.sh", root / "policies", root / "bundles")
    print(f"bundle   {rev}")

    # Dev keys and rules, as dev-init.sh makes them.
    def key(name):
        out = run(TOPAK, "keygen")
        (root / "secrets" / f"{name}.json").write_text(out + "\n")
        return json.loads(out)["public"]

    seats = {s: key(f"seat-{s}") for s in ("a1", "g1", "g2", "g3", "o1", "r1")}
    pretrain = tools["slm_pretrain"]["id"]
    rules = {
        "rules_epoch": 0, "quorum": "all", "min_grant": 2,
        "seats": {s: {"domain": "run" if s == "r1" else "build", "key": k} for s, k in seats.items()},
        "grant_roster": ["g1", "g2", "g3"], "veto_roster": ["o1"],
        "anchor_keys": [key(f"anchor-{i}") for i in (1, 2, 3)],
        "break_glass": {"roster": [key(f"bg-{i}") for i in (1, 2)], "quorum": 2, "tools": [pretrain],
                        "actions": ["RunInvoke"]},
        "erasure_roster": None,
    }
    write_json(root / "rules.json", rules)
    run(TOPAK, "check-rules", root / "rules.json")

    params = {"corpus": sorted(o["digest"] for o in corpus["objects"]),
              "build_tools": sorted(t["id"] for t in tools.values()), "run_tools": [],
              "round_bound": 200, "lease_margin_ms": 500, "after_topic_limit": 64}
    write_json(root / "params.json", params)

    for i in (1, 2, 3):
        write_json(root / f"n{i}.json", {
            "id": i,
            "peers": {str(j): f"127.0.0.1:{7200 + j}" for j in (1, 2, 3)},
            "data_dir": f"run/n{i}", "agent_socket": f"run/n{i}/agent.sock",
            "operator_socket": f"run/n{i}/operator.sock",
            "rules": "rules.json", "params": "params.json", "corpus_dir": "corpus", "bundles_dir": "bundles",
            "opa_sidecar": None, "kafka": None,
            "tools": {t["id"]: {"command": str(wrapper), "args": [], "binary_sha256": t["binary_sha256"],
                                "mcp_tool": name} for name, t in tools.items()},
        })

    write_json(root / "cluster.json", {
        "name": a.name, "corpus": str(a.corpus.resolve()), "corpus_id": corpus["id"], "bundle": rev,
        "tools": {n: t["id"] for n, t in tools.items()}, "objects": params["corpus"],
        "code_pin": pinned_digest(), "topak": str(TOPAK),
    })
    print(f"cluster  {root}  ({len(params['corpus'])} corpus objects)")


if __name__ == "__main__":
    main()
