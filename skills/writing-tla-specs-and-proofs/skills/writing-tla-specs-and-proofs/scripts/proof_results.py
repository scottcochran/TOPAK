#!/usr/bin/env python3
"""Prove <Module>_proof.tla and write its dated proof results file.

    proof_results.py <Module> [--threads N] [--dry-run] [--date YYYY.MM.DD] [--dir D] [--results-dir R]

Runs tlapm --cleanfp --strict on <Module>_proof.tla with a throwaway cache directory, so nothing is taken from an
earlier run and nothing is written beside the module. Only the final obligation count and the exit status are
read; a backend's failure line is noise when another backend closed the obligation.

The results file, <results>/<Module>-proof-results-<date>.txt, prints the sha256 of every local module in the
EXTENDS chain on one Modules: line (dependencies first, the proof module last), the prover's identity and digest
on a Prover: line, the TLC results file that holds the mutations' counterexamples, the named assumptions, every
THEOREM with its statement, every LEMMA by name, and the obligation count. It is written only when every
obligation is proved, and is never overwritten (a rerun that reproduces it says so; one that differs gets a
letter suffix). Exits non-zero on any failed obligation or a prover that is not the pinned one (unless
TLAPM_UNPINNED=1).
"""
import argparse
import os
import re
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.dont_write_bytecode = True  # leave no __pycache__ in the skill directory
import tla_common as t  # noqa: E402


def statements(text):
    """Named ASSUMEs, THEOREMs (with their statement) and LEMMAs, in order."""
    out = []
    pat = re.compile(r"^(ASSUME|THEOREM|LEMMA|COROLLARY|PROPOSITION)\s+(\w+)\s*==", re.M)
    for m in pat.finditer(text):
        rest = text[m.end():]
        stop = re.search(r"^\s*(<\d+>|BY\b|PROOF\b|OBVIOUS\b|OMITTED\b)|^\S", rest, re.M)
        body = rest[:stop.start()] if stop else rest
        body = " ".join(re.sub(r"\\\*[^\n]*", "", body).split())
        out.append((m.group(1), m.group(2), body))
    return out


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("module")
    ap.add_argument("--threads")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--date", default=t.today())
    ap.add_argument("--dir")
    ap.add_argument("--results-dir")
    a = ap.parse_args(argv)
    layout = t.Layout(a.dir, a.results_dir)
    module = a.module.removesuffix(".tla").removesuffix("_proof")
    proof = module + "_proof"
    if not os.path.exists(layout.module(proof)):
        raise SystemExit(f"no {layout.module(proof)}")
    prover = t.require_prover(layout)

    # Read what the results file will describe before the prover runs, so an edit made during the run cannot make
    # the file describe text it did not prove.
    chain = t.module_chain(proof, layout.spec)
    digests = [(m, t.sha256(layout.module(m))) for m in chain]
    stmts = []
    for m in chain:  # the named assumptions the proof may cite are in the modules it extends
        stmts += [s for s in statements(t.strip_comments(t.read(layout.module(m)))) if m == proof or s[0] == "ASSUME"]
    tlc = t.newest(layout, f"{module}-results-*.txt")
    tlc_line = f"{layout.rel(tlc)} sha256 {t.sha256(tlc)}" if tlc else "none"

    cache = tempfile.mkdtemp(prefix=f"tlapm_{module}_")
    try:
        code, out = t.run_group(t.tlapm_cmd(prover, cache, a.threads) + [proof + ".tla"], layout.spec)
    finally:
        shutil.rmtree(cache, ignore_errors=True)
    if any(t.sha256(layout.module(m)) != d for m, d in digests):
        print(f"{proof}.tla or a module it extends changed during the run; no results file written.")
        return 1
    ok_m = re.search(r"All (\d+) obligations? proved", out)
    fail_m = re.search(r"(\d+)/(\d+) obligations? failed", out)
    proved = bool(ok_m) and code == 0 and not fail_m
    if proved:
        count = f"All {ok_m.group(1)} obligations proved."
    elif fail_m:
        count = f"{fail_m.group(1)}/{fail_m.group(2)} obligations failed."
    else:
        count = f"no obligation count (tlapm exit {code})"
    if not proved:
        print("\n".join(out.splitlines()[-200:]), file=sys.stderr)
        print(f"\n{proof}.tla: {count} No results file written.")
        return 1

    lines = [
        f"{layout.project} - {proof}.tla, TLAPS proof results {a.date}",
        f"Generated by proof_results.py; never edited. Command: tlapm --cleanfp --strict --cache-dir <tmp> {proof}.tla",
        "Modules: " + " ".join(f"{layout.rel(layout.module(m))} {d}" for m, d in digests),
        *t.prover_line(prover),
        t.runner_line(os.path.abspath(__file__)),
        "TLC results (the mutations' counterexamples and the witnesses): " + tlc_line,
        "Words: proved means every obligation below was discharged by the prover under the named assumptions and "
        "each theorem's hypotheses; it is not a claim about any constant the assumptions exclude, nor about "
        "running code",
        "",
    ]
    lines += [f"{kind} {name} == {body}" for kind, name, body in stmts if kind != "LEMMA"]
    lemmas = [n for k, n, _ in stmts if k == "LEMMA"]
    if lemmas:
        lines += ["", f"LEMMAS ({len(lemmas)}): " + ", ".join(lemmas)]
    lines += ["", f"Result: {count}"]
    text = "\n".join(lines) + "\n"
    if a.dry_run:
        print(text)
        return 0
    print(t.write_results(layout, f"{module}-proof-results", a.date, text) + f": {count}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
