% Layer: interface · Simulink.Bus definition (a data dictionary entry) · TOPAK source: ADR-0031 §1
% In model-based design the interface is a Bus object: the typed signal that crosses between
% subsystems and that Embedded Coder emits as a C struct. Closed by construction: a bus has
% exactly its elements. The alphabet is a fixed-width boolean vector (no sets in Simulink).
% SCADE's counterpart is the `type Lease = {...}` in ../../02-vocabulary/scade/lease_types.lus.

Confinement = Simulink.Bus;
Confinement.Description = 'ADR-0031 §3: profile digest and attestation rung. Fixed across renewal (A1).';
Confinement.Elements = [ ...
    elem('digest', 'uint8', [32 1], 'SHA-256 of the confinement profile'), ...
    elem('rung',   'uint8', 1,      '0 none declared (Mediated) · 1 launcher · 2 measured boot · 3 confidential VM; Min 0 Max 3')];
Confinement.Elements(2).Min = 0; Confinement.Elements(2).Max = 3;

ActionKind = Simulink.data.dictionary.EnumTypeDefinition;   % Read Draft Invoke Emit Submit Vote Consult Actuate Report
RoundRole  = Simulink.IntEnumType;                           % author = 1, voter = 2

Lease = Simulink.Bus;
Lease.Description = 'ADR-0031 §1: twelve fields, closed. Every field is an authority claim.';
Lease.Elements = [ ...
    elem('principal',   'uint32',      1,      'principal id (interned)'), ...
    elem('seat',        'uint32',      1,      'seat id (interned)'), ...
    elem('persona',     'uint8',       [32 1], 'Persona digest'), ...
    elem('epoch',       'uint64',      1,      'any increment fences the lease'), ...
    elem('fence',       'uint64',      1,      'Paxos log index at grant; the identity'), ...
    elem('rulesEpoch',  'uint64',      1,      'rules epoch at grant'), ...
    elem('bundle',      'uint8',       [32 1], 'bundle revision; fixed across renewal'), ...
    elem('confinement', 'Bus: Confinement', 1, ''), ...
    elem('alphabet',    'boolean',     [9 1],  'one flag per ActionKind; renewal may only clear flags'), ...
    elem('round',       'uint64',      1,      'never reused per seat; fixed across renewal'), ...
    elem('role',        'Enum: RoundRole', 1,  'not ordered; a change is a grant'), ...
    elem('ttl_ms',      'uint64',      1,      'at most T_persona')];

dd = Simulink.data.dictionary.create('topak_lease.sldd');
assignin(dd.getSection('Design Data'), 'Lease', Lease);
assignin(dd.getSection('Design Data'), 'Confinement', Confinement);

function e = elem(name, type, dims, doc)
    e = Simulink.BusElement; e.Name = name; e.DataType = type; e.Dimensions = dims; e.Description = doc;
end
